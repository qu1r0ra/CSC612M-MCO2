"""Read-only review of the 46c1294 strict rerun against the ec31947 runs.

Reads summary.csv from the frozen snapshots and writes tables to this folder.
"""

import csv
from pathlib import Path

RESULTS = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent
FAMILIES = ["dense", "sparse", "model"]
NEW = {f: RESULTS / f"2026-10-05-46c1294-{f}-strict-rerun" for f in FAMILIES}
OLD = {f: RESULTS / f"2026-10-03-ec31947-{f}-full-detached" for f in FAMILIES}
CUDA = [
    "cuda-resident",
    "cuda-resident-graph",
    "cuda-host-origin",
    "cuda-host-origin-pinned",
    "cuda-gpu-origin",
    "cuda-gpu-origin-pinned",
]
CPU = ["cpu-comparator", "cpu-avx2-optimized", "cpu-gpu-origin", "cpu-gpu-origin-pinned"]
ALL = CPU[:2] + CUDA[:4] + CPU[2:3] + CUDA[4:5] + CPU[3:] + CUDA[5:]


def load(path):
    rows = {}
    with open(path / "summary.csv", newline="") as fh:
        for r in csv.DictReader(fh):
            key = (r["input_key"], int(r["bits"]), r["path_label"])
            for k in (
                "median_ms",
                "spread_p90_p10",
                "spread_ratio",
                "speedup_vs_c",
                "speedup_ci_low",
                "speedup_ci_high",
            ):
                r[k] = float(r[k]) if r[k] not in ("", None) else None
            for k in ("stable", "direction_supported", "magnitude_supported", "boundary_inversion"):
                r[k] = {"true": True, "false": False}.get(r[k])
            rows[key] = r
    return rows


def fmt(x, n=3):
    return "—" if x is None else f"{x:.{n}g}"


def claim_class(r):
    if r["direction_supported"]:
        return r["verdict"]
    return "none"


def counts(rows, path):
    sel = [r for k, r in rows.items() if k[2] == path]
    f = sum(1 for r in sel if r["direction_supported"] and r["verdict"] == "faster")
    s = sum(1 for r in sel if r["direction_supported"] and r["verdict"] == "slower")
    m = sum(1 for r in sel if r["magnitude_supported"])
    return f, s, m, len(sel)


def unstable(rows, path):
    sel = [r for k, r in rows.items() if k[2] == path]
    return sum(1 for r in sel if r["stable"] is False), len(sel)


def pct(vals, p):
    vals = sorted(vals)
    i = (len(vals) - 1) * p
    lo, hi = int(i), min(int(i) + 1, len(vals) - 1)
    return vals[lo] + (vals[hi] - vals[lo]) * (i - lo)


def main():
    new = {f: load(NEW[f]) for f in FAMILIES}
    old = {f: load(OLD[f]) for f in FAMILIES}
    out = []
    w = out.append

    w("# 46c1294 strict rerun: review against ec31947\n")
    w("Generated by `analyze.py` from each snapshot's `summary.csv`. Snapshots are unmodified.\n")
    w("Code at the two revisions is identical (only docs and `.gitattributes` differ).\n")

    # 1. Claim counts
    w("\n## 1. Claim counts (faster / slower / magnitude, of 34 cells)\n")
    w("| Path | Family | Old ec31947 | New 46c1294 |")
    w("|---|---|---|---|")
    for p in CUDA[:4] + CUDA[4:5] + CUDA[5:] + ["cpu-gpu-origin", "cpu-gpu-origin-pinned"]:
        for fam in FAMILIES:
            o = counts(old[fam], p)
            n = counts(new[fam], p)
            w(f"| {p} | {fam} | {o[0]} / {o[1]} / {o[2]} | {n[0]} / {n[1]} / {n[2]} |")

    # 2. Stability
    w("\n## 2. Stability (`spread_p90_p10 <= 1.25`)\n")
    w("Unstable cells per path, and the median and 90th percentile of `spread_p90_p10`.\n")
    w("| Path | Family | Old unstable | New unstable | Old median / p90 | New median / p90 |")
    w("|---|---|---|---|---|---|")
    for p in ALL:
        for fam in FAMILIES:
            ou, on = unstable(old[fam], p)
            nu, nn = unstable(new[fam], p)
            osp = [r["spread_p90_p10"] for k, r in old[fam].items() if k[2] == p]
            nsp = [r["spread_p90_p10"] for k, r in new[fam].items() if k[2] == p]
            w(
                f"| {p} | {fam} | {ou}/{on} | {nu}/{nn} | "
                f"{pct(osp, 0.5):.3f} / {pct(osp, 0.9):.3f} | {pct(nsp, 0.5):.3f} / {pct(nsp, 0.9):.3f} |"
            )

    # 3. Direction changes
    w("\n## 3. Cell-by-cell claim changes, old to new\n")
    w("Claim class is `faster`, `slower` (direction supported) or `none`.\n")
    w("| Family | Path | Cells | Same class | Changed |")
    w("|---|---|---|---|---|")
    changes = []
    flip = 0
    for fam in FAMILIES:
        for p in CUDA + ["cpu-gpu-origin", "cpu-gpu-origin-pinned"]:
            same = diff = 0
            for k, r in new[fam].items():
                if k[2] != p:
                    continue
                o = old[fam].get(k)
                if o is None:
                    continue
                a, b = claim_class(o), claim_class(r)
                if a == b:
                    same += 1
                else:
                    diff += 1
                    changes.append((fam, k, a, b, o, r))
                    if {a, b} == {"faster", "slower"}:
                        flip += 1
            w(f"| {fam} | {p} | {same + diff} | {same} | {diff} |")
    w(f"\nOpposite-direction flips (faster vs slower): {flip}.\n")
    w("\n### Changed cells\n")
    w(
        "| Family | Input | Bits | Path | Old | New | Old speedup [CI] | New speedup [CI] | Old/New spread |"
    )
    w("|---|---|---|---|---|---|---|---|---|")
    for fam, k, a, b, o, r in changes:
        w(
            f"| {fam} | {k[0]} | {k[1]} | {k[2]} | {a} | {b} | "
            f"{fmt(o['speedup_vs_c'])} [{fmt(o['speedup_ci_low'])}, {fmt(o['speedup_ci_high'])}] | "
            f"{fmt(r['speedup_vs_c'])} [{fmt(r['speedup_ci_low'])}, {fmt(r['speedup_ci_high'])}] | "
            f"{fmt(o['spread_p90_p10'])} / {fmt(r['spread_p90_p10'])} |"
        )

    # 4. Point estimate reproducibility
    w("\n## 4. Reproducibility of point estimates (new / old speedup)\n")
    w("Ratio of new to old `speedup_vs_c` per cell; 1.00 is perfect reproduction.\n")
    w("| Family | Path | Median | p5 | p95 | Min | Max |")
    w("|---|---|---|---|---|---|---|")
    for fam in FAMILIES:
        for p in ALL[1:]:
            rat = []
            for k, r in new[fam].items():
                if k[2] != p:
                    continue
                o = old[fam][k]
                if r["speedup_vs_c"] and o["speedup_vs_c"]:
                    rat.append(r["speedup_vs_c"] / o["speedup_vs_c"])
            w(
                f"| {fam} | {p} | {pct(rat, 0.5):.3f} | {pct(rat, 0.05):.3f} | {pct(rat, 0.95):.3f} | "
                f"{min(rat):.3f} | {max(rat):.3f} |"
            )

    w("\n### Comparator absolute time (new / old median_ms)\n")
    w("The comparator is every speedup's denominator. Drift here moves all comparisons.\n")
    w("| Family | Median ratio | p5 | p95 | Min | Max |")
    w("|---|---|---|---|---|---|")
    for fam in FAMILIES:
        rat = [
            r["median_ms"] / old[fam][k]["median_ms"]
            for k, r in new[fam].items()
            if k[2] == "cpu-comparator"
        ]
        w(
            f"| {fam} | {pct(rat, 0.5):.3f} | {pct(rat, 0.05):.3f} | {pct(rat, 0.95):.3f} | {min(rat):.3f} | {max(rat):.3f} |"
        )

    w("\n### CI width (median of `ci_high / ci_low`)\n")
    w("| Path | Family | Old | New |")
    w("|---|---|---|---|")
    for p in CUDA[:4]:
        for fam in FAMILIES:

            def wd(rows, p=p):
                v = [
                    r["speedup_ci_high"] / r["speedup_ci_low"]
                    for k, r in rows.items()
                    if k[2] == p and r["speedup_ci_low"]
                ]
                return pct(v, 0.5)

            w(f"| {p} | {fam} | {wd(old[fam]):.4f} | {wd(new[fam]):.4f} |")

    # 5. Borderline
    w("\n## 5. Borderline cells in the new run\n")
    w(
        "Cells without a supported direction whose bootstrap CI lies wholly on one side of 1, or cells that are unstable.\n"
    )
    w("| Family | Input | Bits | Path | Verdict | Speedup [CI] | Spread p90/p10 | Stable |")
    w("|---|---|---|---|---|---|---|---|")
    n_border = 0
    for fam in FAMILIES:
        for k, r in new[fam].items():
            if k[2] not in CUDA + ["cpu-gpu-origin", "cpu-gpu-origin-pinned"]:
                continue
            ci_one_side = r["speedup_ci_low"] and (
                r["speedup_ci_low"] > 1 or r["speedup_ci_high"] < 1
            )
            if (not r["direction_supported"]) and ci_one_side:
                n_border += 1
                w(
                    f"| {fam} | {k[0]} | {k[1]} | {k[2]} | {r['verdict']} | "
                    f"{fmt(r['speedup_vs_c'])} [{fmt(r['speedup_ci_low'])}, {fmt(r['speedup_ci_high'])}] | "
                    f"{fmt(r['spread_p90_p10'])} | {r['stable']} |"
                )
    w(f"\nTotal: {n_border}.\n")

    # 6. Cross-family
    w("\n## 6. Cross-family comparison (new run)\n")
    w("Sparse vs dense: same 34 count/bit cells. Agreement is the same claim class.\n")
    w(
        "| Path | Sparse agrees with dense (new) | (old) | Model agrees with dense at 6 matched cells (new) | (old) |"
    )
    w("|---|---|---|---|---|")
    matched = {
        "8192": "model_layer2.0.shortcut.0.weight",
        "32768": "model_layer3.0.shortcut.0.weight",
        "131072": "model_layer4.0.shortcut.0.weight",
    }
    for p in CUDA:

        def agree(src, p=p):
            a = 0
            n = 0
            for k, r in src["dense"].items():
                if k[2] != p:
                    continue
                s = src["sparse"].get(("sparse_" + k[0], k[1], p))
                if s is not None:
                    n += 1
                    a += claim_class(r) == claim_class(s)
            return a, n

        def agree_model(src, p=p):
            a = n = 0
            for cnt, tname in matched.items():
                for bits in (4, 8):
                    d = src["dense"].get((f"n{cnt}", bits, p))
                    m = src["model"].get((tname, bits, p))
                    if d and m:
                        n += 1
                        a += claim_class(d) == claim_class(m)
            return a, n

        sn, nn = agree(new), agree_model(new)
        so, no = agree(old), agree_model(old)
        w(f"| {p} | {sn[0]}/{sn[1]} | {so[0]}/{so[1]} | {nn[0]}/{nn[1]} | {no[0]}/{no[1]} |")

    w("\n### Dense vs sparse speedup ratio at matched cells (new; sparse/dense)\n")
    w("| Path | Median | Min | Max |")
    w("|---|---|---|---|")
    for p in CUDA + ["cpu-avx2-optimized"]:
        rat = []
        for k, r in new["dense"].items():
            if k[2] != p:
                continue
            s = new["sparse"][("sparse_" + k[0], k[1], p)]
            if r["speedup_vs_c"] and s["speedup_vs_c"]:
                rat.append(s["speedup_vs_c"] / r["speedup_vs_c"])
        w(f"| {p} | {pct(rat, 0.5):.3f} | {min(rat):.3f} | {max(rat):.3f} |")

    w("\n### Dense vs sparse comparator time (sparse/dense median_ms)\n")
    for nm, d in (("new", new), ("old", old)):
        rat = [
            d["sparse"][("sparse_" + k[0], k[1], "cpu-comparator")]["median_ms"] / r["median_ms"]
            for k, r in d["dense"].items()
            if k[2] == "cpu-comparator"
        ]
        w(f"- {nm}: median {pct(rat, 0.5):.3f}, min {min(rat):.3f}, max {max(rat):.3f}")

    # 7. Inversions and correctness
    w("\n## 7. Inversions\n")
    for fam in FAMILIES:
        inv = sum(1 for r in new[fam].values() if r["boundary_inversion"])
        w(f"- {fam}: {inv} inverted cells of {len(new[fam])}.")

    (OUT / "review.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("wrote", OUT / "review.md")


if __name__ == "__main__":
    main()
